/**
 * Figma drift check — the read-back half of the token loop.
 *
 * tokens:figma pushes the JSON into Figma. Nothing stopped someone editing a
 * variable in the Figma UI afterwards, and nothing would have noticed. This
 * closes that: it reads every variable back out of the library and diffs the
 * resolved values against tokens/vela.tokens.json (dark via tokens/vela.dark.tokens.json).
 *
 * Two steps, because Figma's REST API only lets Enterprise plans READ variables
 * too — so the read runs inside the file, like the write:
 *
 *   npm run tokens:figma:read > /tmp/read.js     # run the printed script in the
 *                                                # file (MCP / Scripter), save the
 *                                                # returned text as /tmp/figma.tsv
 *   npm run tokens:figma:check -- /tmp/figma.tsv
 *
 * Exit 1 on any mismatch, so it can gate a Figma library publish the way
 * `verify` gates an npm publish.
 */
import { readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadTokenSet, hexOf, pxOf, msOf, cubicBezierOf } from './tokens-core.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const set = loadTokenSet(root)

// ---------- what the JSON says the library should contain ----------
// `set` resolves aliases per mode: the dark values come from tokens/vela.dark.tokens.json through
// the resolver, the same walk the CSS and the Figma sync make.
const collectionOf = { primitives: 'Primitives', color: 'Color', sizing: 'Sizing', typography: 'Typography', motion: 'Motion' }
const resolveColor = (name, mode) => hexOf(set.resolved(name, mode), name)

const expected = {}
for (const name of set.order) {
  const t = set.all[name]
  const figma = set.vendor(t).figma
  if (!figma) continue
  const key = collectionOf[t.group] + '|' + figma
  if (t.$type === 'color') expected[key] = { css: name, light: resolveColor(name, 'light'), dark: resolveColor(name, 'dark') }
  else if (t.$type === 'dimension') expected[key] = { css: name, value: pxOf(t.$value, name) }
  else if (t.$type === 'number') expected[key] = { css: name, value: t.$value }
  // Figma keeps timing in seconds and an easing as a bezier object (see sync-figma.mjs)
  else if (t.$type === 'duration') expected[key] = { css: name, value: msOf(t.$value, name) / 1000 }
  // A spring's $value aliases its fallback curve; the sync writes the resolved curve (sync-figma.mjs).
  else if (t.$type === 'cubicBezier') expected[key] = { css: name, bezier: cubicBezierOf(set.resolved(name), name) }
}

// ---------- mode 1: print the read script ----------
if (process.argv[2] === '--read' || !process.argv[2]) {
  process.stdout.write(`// Generated by scripts/figma-drift.mjs — reads every variable back, resolved per mode. Do not edit.
const colls = await figma.variables.getLocalVariableCollectionsAsync();
const cById = Object.fromEntries(colls.map(c => [c.id, c]));
const vars = await figma.variables.getLocalVariablesAsync();
const vById = Object.fromEntries(vars.map(v => [v.id, v]));
const hex = c => '#' + [c.r, c.g, c.b].map(x => Math.round(x * 255).toString(16).padStart(2, '0')).join('');
// follow aliases; when an alias crosses into a collection with different modes, match by mode NAME, else first mode
const resolve = (v, modeName) => {
  let cur = v;
  for (let i = 0; i < 12; i++) {
    const c = cById[cur.variableCollectionId];
    const m = c.modes.find(x => x.name === modeName) || c.modes[0];
    const val = cur.valuesByMode[m.modeId];
    if (val && typeof val === 'object' && val.type === 'VARIABLE_ALIAS') { cur = vById[val.id]; continue; }
    return val;
  }
  throw new Error('alias chain too deep at ' + v.name);
};
const lines = [];
for (const v of vars) {
  const c = cById[v.variableCollectionId];
  const key = c.name + '|' + v.name;
  const css = ((v.codeSyntax && v.codeSyntax.WEB) || '').replace(/^var\\(--vela-/, '').replace(/\\)$/, '');
  if (v.resolvedType === 'COLOR') lines.push([key, css, hex(resolve(v, 'Light')), hex(resolve(v, 'Dark'))].join('\\t'));
  else if (v.resolvedType === 'FLOAT' || v.resolvedType === 'TIMING') lines.push([key, css, resolve(v, 'Value')].join('\\t'));
  else if (v.resolvedType === 'STRING') lines.push([key, css, resolve(v, 'Value')].join('\\t'));
  else if (v.resolvedType === 'EASING') { const e = resolve(v, 'Value'), b = e && e.easingFunctionCubicBezier;
    lines.push([key, css, e.type === 'CUSTOM_CUBIC_BEZIER' && b ? 'bezier:' + [b.x1, b.y1, b.x2, b.y2].join(',') : 'preset:' + e.type].join('\\t')); }
}
return lines.join('\\n');
`)
  process.exit(0)
}

// ---------- mode 2: compare a saved read result ----------
// the read script returns one line per variable: key \t css \t light \t dark   (or key \t css \t value,
// where an EASING value reads "bezier:x1,y1,x2,y2" or "preset:NAME")
const actual = {}
for (const line of readFileSync(process.argv[2], 'utf8').split('\n')) {
  if (!line.trim()) continue
  const [key, css, a, b] = line.split('\t')
  actual[key] = b !== undefined ? { css, light: a, dark: b }
    : { css, value: Number(a), string: a, bezier: a.startsWith('bezier:') ? a.slice(7).split(',').map(Number) : undefined }
}
const problems = []
for (const [key, e] of Object.entries(expected)) {
  const a = actual[key]
  if (!a) { problems.push(`MISSING in Figma   ${key}`); continue }
  if ('bezier' in e) {
    // Figma stores numbers as float32 (0.2 reads back as 0.20000000298), so compare within 1e-4
    const ok = a.bezier?.length === 4 && a.bezier.every((n, i) => Math.abs(n - e.bezier[i]) < 1e-4)
    if (!ok) problems.push(`EASING  ${key}: figma="${a.string}" json="cubic-bezier(${e.bezier.join(', ')})"`)
  } else if ('string' in e) {
    if (a.string !== e.string) problems.push(`STRING  ${key}: figma="${a.string}" json="${e.string}"`)
  } else if ('value' in e) {
    if (Math.abs(a.value - e.value) > 0.001) problems.push(`VALUE   ${key}: figma=${a.value} json=${e.value}`)
  } else {
    if (a.light !== e.light) problems.push(`LIGHT   ${key}: figma=${a.light} json=${e.light}`)
    if (a.dark !== e.dark) problems.push(`DARK    ${key}: figma=${a.dark} json=${e.dark}`)
  }
  if (a.css !== e.css) problems.push(`SYNTAX  ${key}: figma="${a.css}" json="${e.css}"`)
}
for (const key of Object.keys(actual)) if (!expected[key]) problems.push(`EXTRA in Figma     ${key} (no token in JSON)`)

console.log(`\n  FIGMA ↔ JSON   ${Object.keys(expected).length} tokens expected · ${Object.keys(actual).length} variables read\n`)
if (problems.length === 0) console.log('  No drift. The library matches tokens/vela.tokens.json exactly.\n')
else { for (const p of problems) console.log('  ' + p); console.log(`\n  ${problems.length} problem(s). Fix in the JSON and re-run tokens:figma — never in Figma alone.\n`) }
process.exit(problems.length ? 1 : 0)
