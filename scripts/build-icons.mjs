/**
 * Icon build — compiles the curated set in scripts/icons.list.json into the three places it lives:
 *
 *   src/icons/generated/<Pascal>.tsx   one zero-dependency React component per glyph (an <svg>)
 *   src/icons/generated/index.ts       the name → component map the Icon component renders from
 *   src/icons/names.ts                 ICON_NAMES (as const) and the IconName union — the closed set
 *   scripts/figma/components/icon.figma.js   the Figma builder: one variant per glyph
 *
 *   npm run icons:build    # write all of the above
 *   npm run icons:check    # rebuild, then fail if the result differs from what is committed (in verify)
 *
 * The geometry is read at build time from the installed `lucide` devDependency
 * (node_modules/lucide/dist/esm/icons/<name>.mjs, see scripts/icons-core.mjs). Nothing from Lucide is
 * imported at runtime: the output is plain JSX, and the core entry stays at zero dependencies
 * (scripts/verify-pack.mjs walks the built module graph to prove it). Every generated file names
 * the Lucide version and its ISC licence; the full notice travels in NOTICE.
 *
 * The <svg> carries viewBox 0 0 24 24, fill none, stroke currentColor, round caps and joins,
 * aria-hidden and focusable="false". It carries NO width, height or stroke-width: Icon.css binds
 * --vela-icon-size* and --vela-icon-stroke, and a presentation attribute would only be a second,
 * silent source for the same value. Generated files are never edited by hand — change the list or
 * this script and rebuild.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { root, loadList, lucideVersion, glyphNode, pascal } from './icons-core.mjs'

const list = loadList()
const version = lucideVersion()
if (version !== list.lucide)
  throw new Error(`scripts/icons.list.json was reviewed against lucide ${list.lucide}, but ${version} is installed. Review the glyphs at the new version, then update "lucide" in the list.`)

const LICENCE = `lucide ${version}, ISC — Copyright (c) 2026 Lucide Icons and Contributors (see NOTICE)`
const ATTRS = ['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points']
const TAGS = ['path', 'circle', 'ellipse', 'rect', 'line', 'polyline', 'polygon']

const nodes = []
for (const name of list.icons) {
  const node = await glyphNode(name)
  for (const [tag, attrs] of node) {
    if (!TAGS.includes(tag)) throw new Error(`${name}: unexpected element <${tag}>`)
    for (const k of Object.keys(attrs)) if (!ATTRS.includes(k)) throw new Error(`${name}: unexpected attribute ${k} on <${tag}>`)
  }
  nodes.push({ name, component: pascal(name), node })
}

const attrString = (attrs) => ATTRS.filter((k) => k in attrs).map((k) => `${k}="${attrs[k]}"`).join(' ')

// ---------- React ----------
const outDir = join(root, 'src/icons/generated')
mkdirSync(outDir, { recursive: true })
const written = new Set()
const write = (file, body) => { writeFileSync(join(outDir, file), body); written.add(file) }

for (const { name, component, node } of nodes) {
  write(`${component}.tsx`, `// Generated by scripts/build-icons.mjs from scripts/icons.list.json — do not edit.
// Glyph "${name}": ${LICENCE}.
import type { GlyphProps } from '../glyph'

export function ${component}(props: GlyphProps) {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" focusable="false" {...props}>
${node.map(([tag, attrs]) => `      <${tag} ${attrString(attrs)} />`).join('\n')}
    </svg>
  )
}
`)
}

write('index.ts', `// Generated by scripts/build-icons.mjs from scripts/icons.list.json — do not edit.
// Glyphs: ${LICENCE}.
// The name → component map Icon renders from. Internal: the public API is Icon and ICON_NAMES
// (src/index.ts); the individual glyph components are not exported from the package.
import type { Glyph } from '../glyph'
import type { IconName } from '../names'
${nodes.map((n) => `import { ${n.component} } from './${n.component}'`).join('\n')}

export const GLYPHS: Readonly<Record<IconName, Glyph>> = {
${nodes.map((n) => `  '${n.name}': ${n.component},`).join('\n')}
}
`)

for (const f of readdirSync(outDir)) if (!written.has(f)) rmSync(join(outDir, f))

writeFileSync(join(root, 'src/icons/names.ts'), `// Generated by scripts/build-icons.mjs from scripts/icons.list.json — do not edit.
// The closed Icon set: ${nodes.length} glyphs from ${LICENCE}.
// A name not in this list does not exist: \`<Icon name="shield" />\` is a compile error.

export const ICON_NAMES = [
${nodes.map((n) => `  '${n.name}',`).join('\n')}
] as const

export type IconName = (typeof ICON_NAMES)[number]
`)

// ---------- Figma ----------
// The builder carries the geometry inline: it runs inside Figma, where node_modules does not exist.
const figmaFile = join(root, 'scripts/figma/components/icon.figma.js')
const figma = `// @page Icon
// @set  Icon
// Generated by scripts/build-icons.mjs from scripts/icons.list.json — do not edit.
// Glyph geometry: ${LICENCE}.
//
// Icon — ${nodes.length} variants, one per curated glyph (\`Glyph=<name>\`). Each variant is a box bound to
// icon/size (16, the code's \`size="regular"\`) holding one flattened vector, \`Glyph / <name>\`, drawn on
// Lucide's 24-unit grid and scaled into the box (constraints SCALE), so binding an instance to
// icon/size-small or icon/size-large scales the geometry with it. The stroke binds the colour variable
// icon/strong (the code's \`tone="default"\`); swapping it for icon/default is \`tone="muted"\`.
//
// Stroke weight: icon/stroke is 2 in grid units. Figma's stroke weight is in canvas pixels and does not
// scale with the box, and a variable cannot be bound to a product, so the weight is written as the
// value the code renders at regular — icon/stroke × icon/size ÷ 24 = 1.33 — read from the two
// variables when the script runs. At small and large an instance keeps 1.33 where the code renders
// 1 and 1.67; that is the recorded gap (guidelines/components/icon.md, Figma mapping).
// @allow absolute-children a glyph box holds drawn geometry on Lucide's 24-unit grid; there is nothing to lay out
// @allow raw-size the glyph vector's box is its own geometry, scaled with the icon/size box by constraints

const GLYPHS = [
${nodes.map((n) => `  [${JSON.stringify(n.name)}, ${JSON.stringify(n.node.map(([tag, attrs]) => `<${tag} ${attrString(attrs)}/>`).join(''))}],`).join('\n')}
];
const value = v => v.valuesByMode[Object.keys(v.valuesByMode)[0]];
const SIZE = num('icon/size'), STROKE = num('icon/stroke');
const weight = Math.round(value(STROKE) * value(SIZE) / 24 * 100) / 100;
const variants = [];
for (const [name, body] of GLYPHS) {
  const svg = figma.createNodeFromSvg('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + body + '</svg>');
  const c = figma.createComponent();
  c.name = 'Glyph=' + name; c.fills = []; c.clipsContent = false; c.resize(24, 24);
  c.appendChild(svg); svg.x = 0; svg.y = 0;
  const glyph = figma.flatten(svg.children, c);
  svg.remove();
  glyph.name = 'Glyph / ' + name;
  glyph.fills = []; glyph.strokes = [paint('icon/strong')];
  glyph.strokeCap = 'ROUND'; glyph.strokeJoin = 'ROUND';
  glyph.constraints = { horizontal: 'SCALE', vertical: 'SCALE' };
  c.setBoundVariable('width', SIZE); c.setBoundVariable('height', SIZE);
  glyph.strokeWeight = weight;
  variants.push(c);
}

const set = figma.combineAsVariants(variants, page);
set.name = SET; set.x = 0; set.y = 0;
const COLS = 10;
grid(set, p => [GLYPHS.findIndex(g => g[0] === p.Glyph) % COLS, Math.floor(GLYPHS.findIndex(g => g[0] === p.Glyph) / COLS)], 48, 48, 32);
set.resize(32 * 2 + 48 * COLS, 32 * 2 + 48 * Math.ceil(GLYPHS.length / COLS));

return { created: SET, variants: variants.length, setId: set.id };
`
writeFileSync(figmaFile, figma)

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(1)
console.log(`icons:build  ${nodes.length} glyphs from lucide ${version} → src/icons/generated/ (${written.size} files), src/icons/names.ts`)
console.log(`icons:build  scripts/figma/components/icon.figma.js  ${kb(figma)} KB`)
