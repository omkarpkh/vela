/**
 * Writes `src/grammar/fold-table.ts`: the code points where JavaScript's `toLowerCase` differs from
 * Unicode simple case folding, so `src/grammar/fold.ts` can fold exactly (filter-grammar.md, Case
 * folding).
 *
 * Simple case folding is the C (common) and S (simple) mappings of `CaseFolding.txt`, vendored next
 * to this script, unchanged, for the Unicode version the repo's Node ships. A code point with no C or
 * S mapping folds to itself. For every code point, the fold is `toLowerCase` of that code point
 * alone, unless the table says otherwise; the table holds each code point where the two differ.
 *
 * `toLowerCase` comes from the Node that runs this script, so the script refuses to run when that
 * Node's Unicode version (`process.versions.unicode`) is not the file's. A new Node with a new
 * Unicode version means a new CaseFolding.txt and a new table, in the same change.
 *
 *   node scripts/grammar/build-fold-table.mjs           write the table
 *   node scripts/grammar/build-fold-table.mjs --check   exit 1 if the committed table is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export const DATA = join(here, 'CaseFolding.txt')
export const OUT = join(here, '..', '..', 'src', 'grammar', 'fold-table.ts')

/** The file's Unicode version, from its first line: "# CaseFolding-17.0.0.txt". */
export function dataVersion(text) {
  const m = /^# CaseFolding-(\d+\.\d+\.\d+)\.txt/.exec(text)
  if (!m) throw new Error('CaseFolding.txt: the first line names no Unicode version.')
  return m[1]
}

/** Whether Node's Unicode version ("17.0") is the file's ("17.0.0"). */
export const sameVersion = (node, data) => `${node}.0.0`.split('.').slice(0, 3).join('.') === data

/** Every C and S entry of the file, as [code point, folded code point], in file order. */
export function simpleFolds(text) {
  const out = []
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F]{4,6}); ([CS]); ([0-9A-F]{4,6}); #/.exec(line)
    if (m) out.push([parseInt(m[1], 16), parseInt(m[3], 16)])
  }
  return out
}

/** [code point, its simple fold] for every code point where `toLowerCase` of it alone differs. */
export function foldTable(text) {
  const folds = new Map(simpleFolds(text))
  const table = []
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue
    const to = folds.get(cp) ?? cp
    if (String.fromCodePoint(cp).toLowerCase() !== String.fromCodePoint(to)) table.push([cp, to])
  }
  return table
}

const hex = (n) => `0x${n.toString(16).padStart(4, '0')}`

export function render(text) {
  const version = dataVersion(text)
  const table = foldTable(text)
  const rows = []
  for (let i = 0; i < table.length; i += 6) rows.push(`  ${table.slice(i, i + 6).map(([a, b]) => `[${hex(a)}, ${hex(b)}]`).join(', ')},`)
  return `// Generated by scripts/grammar/build-fold-table.mjs from scripts/grammar/CaseFolding.txt. Do not edit.
//
// Every code point where \`toLowerCase\`, applied to that code point alone, differs from Unicode
// ${version} simple case folding (CaseFolding.txt's C and S mappings; no mapping means the code point
// folds to itself). ${table.length} entries. Each pair is [code point, its simple fold].
export const UNICODE_VERSION = '${version}'

export const FOLD_TABLE: readonly (readonly [number, number])[] = [
${rows.join('\n')}
]
`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = readFileSync(DATA, 'utf8')
  const version = dataVersion(text)
  if (!sameVersion(process.versions.unicode, version)) {
    console.error(`build-fold-table: this Node has Unicode ${process.versions.unicode}, and CaseFolding.txt is ${version}. Vendor the file for ${process.versions.unicode}, or run the Node the repo ships.`)
    process.exit(1)
  }
  const source = render(text)
  if (process.argv.includes('--check')) {
    let committed = ''
    try { committed = readFileSync(OUT, 'utf8') } catch { /* missing is stale */ }
    if (committed !== source) {
      console.error('build-fold-table: src/grammar/fold-table.ts is stale. Run node scripts/grammar/build-fold-table.mjs.')
      process.exit(1)
    }
    console.log(`build-fold-table: up to date (Unicode ${version}, ${foldTable(text).length} entries).`)
  } else {
    writeFileSync(OUT, source)
    console.log(`build-fold-table: wrote src/grammar/fold-table.ts (Unicode ${version}, ${foldTable(text).length} entries).`)
  }
}
