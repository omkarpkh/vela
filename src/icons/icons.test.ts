import { readFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, it, expect } from 'vitest'
import { ICON_NAMES } from './names'
import { GLYPHS } from './generated'
// Shared with scripts/build-icons.mjs, so the build and these checks read Lucide the same way.
import { loadList, lucideVersion, aliasTable, canonical, featherDerived, pascal } from '../../scripts/icons-core.mjs'

const root = process.cwd()
const list = loadList() as { lucide: string; icons: string[] }

// [[rule: icon-set-is-generated]]
describe('the curated icon set is one list, compiled', () => {
  it('ICON_NAMES is scripts/icons.list.json, in order', () => {
    expect([...ICON_NAMES]).toEqual(list.icons)
  })

  it('the generated index maps exactly those names, and one file exists per glyph', () => {
    expect(Object.keys(GLYPHS)).toEqual(list.icons)
    const files = readdirSync(resolve(root, 'src/icons/generated')).filter((f) => f !== 'index.ts').sort()
    expect(files).toEqual(list.icons.map((n) => `${pascal(n)}.tsx`).sort())
  })

  it('every generated file says it is generated, names the Lucide version and its licence', () => {
    for (const n of list.icons) {
      const src = readFileSync(resolve(root, 'src/icons/generated', `${pascal(n)}.tsx`), 'utf8')
      expect(src).toMatch(/^\/\/ Generated by scripts\/build-icons\.mjs .* do not edit\./)
      expect(src).toContain(`Glyph "${n}": lucide ${list.lucide}, ISC`)
      expect(src).not.toMatch(/from ['"]lucide/)
    }
  })

  it('was reviewed against the Lucide version that is installed and pinned', () => {
    const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
    expect(lucideVersion()).toBe(list.lucide)
    expect(pkg.devDependencies.lucide).toBe(list.lucide)
    expect(pkg.dependencies ?? {}).toEqual({})
  })

  it('uses only canonical Lucide names; the three aliases in the brief resolve to the names used', () => {
    const table = aliasTable()
    for (const n of list.icons) expect(canonical(n, table), n).toBe(n)
    expect(canonical('filter', table)).toBe('funnel')
    expect(canonical('trash-2', table)).toBe('trash')
    expect(canonical('history', table)).toBe('rotate-ccw-clock')
  })

  it('every glyph has a row in the spec, in the same order', () => {
    const md = readFileSync(resolve(root, 'guidelines/components/icon.md'), 'utf8')
    const section = md.match(/^## Glyphs\n([\s\S]*?)(?=^## )/m)![1]
    const rows = [...section.matchAll(/^\| `([a-z0-9-]+)` \|/gm)].map((m) => m[1])
    expect(rows).toEqual(list.icons)
  })

  it('NOTICE lists exactly the curated glyphs Lucide says derive from Feather', () => {
    const notice = readFileSync(resolve(root, 'NOTICE'), 'utf8')
    const block = notice.match(/these\s+are the Feather-derived glyphs[^:]*:\s*([\s\S]*?)\.\n/)![1]
    const listed = block.replace(/\s+/g, ' ').trim().split(', ')
    expect(listed).toEqual(featherDerived(list.icons))
  })
})
